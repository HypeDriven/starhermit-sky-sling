// Writes the native play scripts (tests/native/*.play) from the rules: the
// keyboard bot (tools/plan.mjs) aims each shot with the arrow keys as
// main.ts does (0.5 m/s a press, the aim kept between shots and rounds) and
// the scripts wait each shot's exact settle time (one rules tick per fixed
// step, one fixed step per render-check frame). Today's Daily depends on the
// date: tests/native.mjs writes it with dailyPlay() at test time.
//   node tools/gen-plays.mjs
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { planLevel } from './plan.mjs';

const require = createRequire(import.meta.url);
const C = require('../content.js');
const S = require('../session.js');
const root = join(dirname(fileURLToPath(import.meta.url)), '..');

/** The lines that play one planned stage by keys, ending on its results. */
function shotLines(plan) {
  const out = [];
  plan.shots.forEach((s, i) => {
    out.push(`# shot ${i + 1}: vx ${s.vx}, vy ${s.vy} (${s.ticks} ticks)`);
    for (const [key, n] of s.keys) for (let k = 0; k < n; k++) out.push(`key ${key} 1`);
    out.push('key Space 1');
    if (i < plan.shots.length - 1) out.push(`frames ${s.ticks + 15}`);
  });
  out.push(`until 600 ${plan.won ? 'Stage Clear!' : 'Out of Shots'}`, 'frames 10');
  return out;
}
/** A level the session builds for a mode (session.js startRound), planned from `aim`. */
function sessionLevel(mode, ref) {
  const s = new S.Session();
  s.startRound(mode, ref);
  return s.level;
}

export function journeyPlay() {
  const lines = ['# Journey stages 1–5 by keys from Play (the furthest unlocked stage), each to its results, then Next stage; Menu at the end.',
    '# viewport 1280x800@1', '# Generated by tools/gen-plays.mjs from the rules (tools/plan.mjs).',
    'until 600 Daily Challenge', 'frames 20', 'click =Play', 'until 120 Collapse every Bumble', 'frames 20'];
  let aim = { vx: 9, vy: 7 };
  for (let i = 0; i < 5; i++) {
    const p = planLevel(C.getLevel(i), aim);
    if (!p.won) throw new Error(`stage ${i + 1} not won by the bot`);
    aim = p.aim;
    lines.push(`# stage ${i + 1}`, ...shotLines(p), `expect ${p.total} points`);
    if (i === 0) lines.push('save journey-1-clear', 'expect Achievement unlocked: Demolition Eye');
    if (i < 4) lines.push('click =Next stage', 'until 120 Collapse every Bumble', 'frames 20');
  }
  lines.push('click =Menu', 'until 120 Journey: 5 / 45 stages cleared', 'frames 10', 'click =Journey', 'until 120 Journey stages', 'frames 10', 'save journey-grid', 'expect Stage 5, ');
  return lines.join('\n') + '\n';
}

export function dailyPlay(date) {
  const lines = [`# The Daily Challenge of ${date.toISOString().slice(0, 10)} by keys from the title.`, '# viewport 1280x800@1',
    '# Generated at test time by tests/native.mjs (tools/gen-plays.mjs dailyPlay).',
    'until 600 Daily Challenge', 'frames 20', 'click =Daily Challenge', 'until 120 Collapse every Bumble', 'frames 20'];
  const p = planLevel(C.makeDaily(date), { vx: 9, vy: 7 });
  lines.push(...shotLines(p), `expect ${p.total} points`, 'expect Daily');
  return lines.join('\n') + '\n';
}

export function challengePlay() {
  const lines = ['# Challenge (stage 13 with one shot fewer) from the mode list, by keys, then Retry.', '# viewport 960x540@1',
    '# Generated by tools/gen-plays.mjs from the rules (tools/plan.mjs).',
    'until 600 Daily Challenge', 'frames 20', 'click =Journey', 'until 120 Journey stages', 'frames 10', 'click =Back', 'until 120 Select a mode', 'frames 10',
    'click =Challenge', 'until 120 Collapse every Bumble', 'frames 20'];
  const lv = sessionLevel('challenge', 12);
  const p = planLevel(lv, { vx: 9, vy: 7 });
  lines.push(...shotLines(p), `expect ${p.total} points`, 'save challenge-results', 'click =Retry', 'until 120 Collapse every Bumble', 'frames 10', 'expect Challenge');
  return lines.join('\n') + '\n';
}

/** Practice stage 9 sideways on a phone: a shot by keys (fast-forwarded), undo from the tray, the pause panel's Help and Settings, leave. */
export function practicePlay() {
  const lines = ['# Practice on a phone held sideways (DPR 3): stage 9 from the stage grid, one shot by keys fast-forwarded, undo from the tray,',
    '# then the pause panel: Help, Settings (left-handed controls on), Resume, Pause, Leave round.', '# viewport 844x390@3',
    '# Generated by tools/gen-plays.mjs from the rules (tools/plan.mjs).',
    'until 600 Daily Challenge', 'frames 20', 'touch =Journey', 'until 120 Journey stages', 'frames 10', 'touch =Back', 'until 120 Select a mode', 'frames 10',
    'touch =Practice', 'until 120 Practice stages', 'frames 10', 'touch =Stage 9', 'until 120 Collapse every Bumble', 'frames 20'];
  const lv = C.getLevel(8);
  const p = planLevel(lv, { vx: 9, vy: 7 });
  const first = { ...p, shots: [p.shots[0]] };
  const s1 = first.shots[0];
  for (const [key, n] of s1.keys) for (let k = 0; k < n; k++) lines.push(`key ${key} 1`);
  // fast-forward the shot (S): the session settles it at once into the same end state
  lines.push('key Space 1', 'frames 5', 'key KeyS 1', 'frames 10', `expect ${lv.shots - 1}`, 'save practice-after-shot', 'touch =Undo shot (practice)', 'frames 10',
    `expect ${lv.shots}`, 'save practice-undone',
    'touch =Pause', 'until 60 Paused', 'frames 10', 'save practice-paused', 'touch =Help #2', 'until 60 Materials', 'frames 10', 'save practice-help',
    'touch =Close', 'until 60 Paused', 'frames 10', 'touch =Settings', 'until 60 Left-handed controls', 'frames 10', 'touch =Left-handed controls', 'frames 10',
    'save practice-settings', 'touch =Done', 'until 60 Paused', 'frames 10', 'touch =Resume', 'frames 20', 'save practice-lefty',
    'touch =Pause', 'until 60 Paused', 'frames 10', 'touch =Leave round', 'until 60 Daily Challenge', 'frames 10', 'expect Practice');
  return lines.join('\n') + '\n';
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(join(root, 'tests/native/journey.play'), journeyPlay());
  writeFileSync(join(root, 'tests/native/challenge.play'), challengePlay());
  writeFileSync(join(root, 'tests/native/practice-landscape.play'), practicePlay());
  console.log('wrote tests/native/journey.play, challenge.play, practice-landscape.play');
}
